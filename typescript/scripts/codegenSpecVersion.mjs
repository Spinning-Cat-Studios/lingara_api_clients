// Writes src/generated/specVersion.ts from the generator view's
// `info.version`: the frozen /v1 version the library's types describe
// (ADR 30.9.26a §4). The version observer warns when a response is served
// from another one.
//
// Usage: node scripts/codegenSpecVersion.mjs <view.json> <out.ts>
// Node only, no dependencies.

import { readFileSync, writeFileSync } from "node:fs";

const [viewPath, outPath] = process.argv.slice(2);
if (!viewPath || !outPath) {
  console.error("usage: codegenSpecVersion.mjs <view.json> <out.ts>");
  process.exit(2);
}

const version = JSON.parse(readFileSync(viewPath, "utf8")).info?.version;
if (typeof version !== "string" || version === "") {
  console.error(`${viewPath}: no info.version`);
  process.exit(1);
}

writeFileSync(
  outPath,
  `// Generated by scripts/codegenSpecVersion.mjs from the generator view's
// info.version. Do not edit: run \`make codegen-typescript\`.

/** The /v1 version this library's types were generated from. */
export const GENERATED_FOR_VERSION = ${JSON.stringify(version)};
`,
);
