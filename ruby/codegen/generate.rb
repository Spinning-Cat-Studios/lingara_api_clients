# frozen_string_literal: true

# ruby/codegen/generate.rb — the half of the Ruby library openapi-generator
# does not write. It reads the generator view (spec/generator/openapi.3.0.json)
# and VERSION, and writes three files into lib/lingara/ (or --out <dir>):
#
#   operations.rb  the nine routes keyed by operationId: method, path, path
#                  parameters, request and response models, whether a token is
#                  needed, and for a stream its events, their branch classes
#                  and its terminal table (from the view's endsOn)
#   streams.rb     one module per stream union, matching any of its branches
#                  with `===` and decoding one event by name
#   version.rb     VERSION, GEM_VERSION and GENERATED_FOR_VERSION
#
# It refuses a models directory beside its output (<out>/models/) holding a
# file named after a union: the ignore file passed to openapi-generator names
# the four unions by path, and a fifth stream it does not name would
# otherwise ship two types for one union. Standard library only; not shipped
# in the gem.

require "json"
require "optparse"

module LingaraCodegen
  ROOT = File.expand_path("../..", __dir__)
  HEADER = "# Generated by ruby/codegen/generate.rb from the generator view. DO NOT EDIT.\n"

  module_function

  def snake(name)
    name.gsub(/([a-z\d])([A-Z])/, '\1_\2').gsub(/([A-Z]+)([A-Z][a-z])/, '\1_\2').downcase
  end

  def ref_name(ref)
    ref&.split("/")&.last
  end

  # RubyGems' spelling of a SemVer pre-release: every `-` becomes `.pre.`,
  # as Gem::Version itself does.
  def gem_version(version)
    version.gsub("-", ".pre.")
  end

  # One operation per `paths` entry and one per x-lingara-streams entry,
  # sorted by operationId so the output never depends on key order.
  def operations(view)
    ops = []
    view.fetch("paths", {}).each do |path, item|
      item.each do |method, op|
        next unless op.is_a?(Hash) && op["operationId"]
        ops << json_operation(path, method, op)
      end
    end
    view.fetch("x-lingara-streams", []).each { |entry| ops << stream_operation(view, entry) }
    ops.sort_by { |op| op[:id] }
  end

  def json_operation(path, method, op)
    schema = op.dig("responses", "200", "content", "application/json", "schema")
    {
      id: op["operationId"], method: method.upcase, path: path, path_params: path_params(path),
      needs_token: !Array(op["security"]).empty?, request_body: ref_name(op.dig("requestBody", "content", "application/json", "schema", "$ref")),
      response: ref_name(schema && schema["$ref"])
    }
  end

  def stream_operation(view, entry)
    union = entry.fetch("union")
    mapping = view.dig("components", "schemas", union, "discriminator", "mapping") ||
      abort("generate.rb: #{union} has no discriminator mapping in the view")
    events = entry.fetch("events").to_h { |name| [name, ref_name(mapping[name]) || abort("generate.rb: #{union} has no branch for #{name}")] }
    {
      id: entry.fetch("operationId"), method: entry.fetch("method").upcase, path: entry.fetch("path"),
      path_params: path_params(entry["path"]), needs_token: !Array(entry["scopes"]).empty?,
      request_body: ref_name(entry["requestBody"]), response: nil,
      stream: {union: union, events: events, ends: endings(view, entry, events)}
    }
  end

  # CONTRACT.md K5's rule over endsOn (ADR 29.9.26ai): the entry's error event
  # raises, an ending event whose data is `Done` ends quietly, and any other
  # ending event is yielded and then ends the stream.
  def endings(view, entry, events)
    ends_on = entry["endsOn"] || abort("generate.rb: #{entry["operationId"]}: no endsOn; the view predates ADR 29.9.26ai")
    ends_on.to_h do |name|
      branch = events[name] || abort("generate.rb: #{entry["operationId"]}: endsOn names unknown event #{name}")
      data = view.dig("components", "schemas", branch, "properties", "data", "$ref")
      outcome = if name == entry["error"] then :raise
      elsif ref_name(data) == "Done" then :quiet
      else :yield
      end
      [name, outcome]
    end
  end

  def path_params(path)
    path.scan(/\{([^}]+)\}/).flatten
  end

  def operations_rb(ops)
    rows = ops.map { |op| "    #{op[:id].inspect} => #{operation_literal(op)}" }
    <<~RUBY
      #{HEADER.chomp}

      module Lingara
        # Every operation's route, keyed by operationId: from `paths` for a JSON
        # operation and from `x-lingara-streams` for a stream. A stream's `ends`
        # is its terminal table: :yield (yielded, then the stream ends), :quiet
        # (a Done payload, never yielded) and :raise (the error event).
        OPERATIONS = {
      #{rows.join(",\n")}
        }.freeze
      end
    RUBY
  end

  def operation_literal(op)
    fields = [
      "method: #{op[:method].inspect}", "path: #{op[:path].inspect}", "path_params: #{op[:path_params].inspect}.freeze",
      "needs_token: #{op[:needs_token]}", "request_body: #{op[:request_body].inspect}", "response: #{op[:response].inspect}"
    ]
    if (stream = op[:stream])
      events = stream[:events].map { |name, branch| "#{name.inspect} => #{branch.inspect}" }.join(", ")
      ends = stream[:ends].map { |name, outcome| "#{name.inspect} => #{outcome.inspect}" }.join(", ")
      fields << "stream: {union: #{stream[:union].inspect}, events: {#{events}}.freeze, ends: {#{ends}}.freeze}.freeze"
    else
      fields << "stream: nil"
    end
    "{\n      #{fields.join(",\n      ")}\n    }.freeze"
  end

  def streams_rb(ops)
    modules = ops.filter_map { |op| op[:stream] && union_module(op) }
    <<~RUBY
      #{HEADER.chomp}

      module Lingara
      #{modules.join("\n")}end
    RUBY
  end

  def union_module(op)
    stream = op[:stream]
    branches = stream[:events].map { |name, branch| "      #{name.inspect} => #{branch}" }.join(",\n")
    <<~RUBY
        # One event of #{op[:id]}'s stream: `case event in #{stream[:union]}` matches
        # any of its branches. The error branch, and a Done-bodied one, are never
        # yielded.
        module #{stream[:union]}
          BRANCHES = {
      #{branches}
          }.freeze
      
          def self.===(other)
            BRANCHES.value?(other.class)
          end
      
          # The branch for a known event name, decoded from its `data` JSON text,
          # or nil for an unknown name. A known event whose data is not a JSON
          # object, or that its branch refuses, raises TransportError
          # :malformed_event.
          def self.decode(name, data)
            branch = BRANCHES[name]
            branch && Lingara::Decoding.event(branch, name, data)
          end
        end
    RUBY
  end

  def version_rb(version, generated_for)
    <<~RUBY
      #{HEADER.chomp}

      module Lingara
        # This library's released version, SemVer, sent in every User-Agent (K6).
        VERSION = #{version.inspect}

        # The same version in RubyGems' spelling, which the gemspec uses.
        GEM_VERSION = #{gem_version(version).inspect}

        # The /v1 version this library's models were generated from. A response
        # served under another version logs one warning per version id.
        GENERATED_FOR_VERSION = #{generated_for.inspect}
      end
    RUBY
  end

  def refuse_generated_unions(out, ops)
    ops.each do |op|
      next unless op[:stream]
      file = File.join(out, "models", "#{snake(op[:stream][:union])}.rb")
      next unless File.exist?(file)
      abort("generate.rb: #{file} is openapi-generator's copy of the union #{op[:stream][:union]}; " \
            "name it in codegen/ruby.openapi-generator-ignore")
    end
  end

  def run(argv)
    options = {out: File.join(ROOT, "ruby/lib/lingara"), view: File.join(ROOT, "spec/generator/openapi.3.0.json"), version: File.join(ROOT, "VERSION")}
    OptionParser.new do |o|
      o.on("--out DIR") { |v| options[:out] = v }
      o.on("--view FILE") { |v| options[:view] = v }
      o.on("--version FILE") { |v| options[:version] = v }
    end.parse!(argv)
    view = JSON.parse(File.read(options[:view]))
    ops = operations(view)
    refuse_generated_unions(options[:out], ops)
    version = File.read(options[:version]).strip
    files = {
      "operations.rb" => operations_rb(ops),
      "streams.rb" => streams_rb(ops),
      "version.rb" => version_rb(version, view.dig("info", "version"))
    }
    files.each { |name, text| File.write(File.join(options[:out], name), text) }
  end
end

LingaraCodegen.run(ARGV) if $PROGRAM_NAME == __FILE__
